"""Generate report/appendix_tables.tex -- the supplementary tables of Appendix C.

Same rule as `generate_report_numbers.py`: nothing is hand-typed. Each table is emitted from the
artefact that produced it, so a changed result propagates on the next build instead of silently
disagreeing with the main text.

These tables deliberately do NOT duplicate the main text. They give the breakdowns the chapters
summarise: every CFAR variant rather than the per-condition best, both gates rather than the primary
one, per-condition localisation rather than the pooled figure, and the per-sequence and per-seed
CARRADA detail behind Chapter 7's figures.

Usage:  python scripts/make_appendix_tables.py
"""
from __future__ import annotations

import json
import os
import sys

import pandas as pd
import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
E6 = os.path.join(ROOT, "experiments", "e6_nms_audit")
FINAL = os.path.join(E6, "results", "final")
CARFINAL = os.path.join(E6, "results", "p4_carrada", "r1_test")
OUT = os.path.join(ROOT, "report", "appendix_tables.tex")

COND = ("isolated", "masking", "clutter", "clutter_edge", "multi", "mixed", "unresolved")
NICE = {"clutter_edge": "clutter edge", "multi": "multi-target"}
METHODS = ("CA", "GO", "OS", "SO", "DL")
LABEL = {"DL": "TinyCNN"}

out: list[str] = []


def w(s=""):
    out.append(s)


def nm(c):
    return NICE.get(c, c).replace("_", " ")


def meth(m):
    return LABEL.get(m, m + "-CFAR")


def radius():
    fp = yaml.safe_load(open(os.path.join(ROOT, "configs", "final_protocol.yaml"),
                             encoding="utf-8"))
    return int(fp["evaluation"]["nms_size"])


def table(caption, label, colspec, header, rows, note=None):
    w(r"\begin{table}[htbp]")
    w(r"\centering\small")
    w(r"\caption{%s}" % caption)
    w(r"\label{%s}" % label)
    w(r"\begin{tabular}{@{}%s@{}}" % colspec)
    w(r"\toprule")
    w(header + r" \\")
    w(r"\midrule")
    for r in rows:
        w(r + r" \\")
    w(r"\bottomrule")
    w(r"\end{tabular}")
    if note:
        w(r"\vspace{2pt}")
        w(r"{\footnotesize %s\par}" % note)
    w(r"\end{table}")
    w()


def main():
    R = radius()
    loc = pd.read_csv(os.path.join(FINAL, "localization_final_r%d.csv" % R))
    pfa = pd.read_csv(os.path.join(FINAL, "measured_pfa_final_r%d_tol1.csv" % R))
    b3 = pd.read_csv(os.path.join(FINAL, "bootstrap_final_r%d_tol3.csv" % R))
    R1 = json.load(open(os.path.join(CARFINAL, "r1_summary.json")))

    w("% " + "=" * 74)
    w("% AUTO-GENERATED by scripts/make_appendix_tables.py -- DO NOT EDIT BY HAND.")
    w("% " + "=" * 74)
    w()

    # ---------------------------------------------------------------- C.1 Pd, every arm, both gates
    rows = []
    for c in COND:
        for gate in (1, 3):
            d = loc[(loc.gate == gate) & (loc.group == c)].set_index("method")
            cells = [" ".join(nm(c).split()) if gate == 1 else "", str(gate)]
            cells += ["%.4f" % d.loc[m, "pd"] for m in METHODS]
            rows.append(" & ".join(cells))
    table("Detection probability for every arm on every scored condition, at both matching gates, "
          "on the held-out split at matched measured $\\Pfa$. The main text reports only the "
          "best CFAR variant per condition; this table gives all four. TinyCNN values are means "
          "over \\TinySeeds{} seeds.",
          "tab:appPdAll", "llccccc",
          r"\textbf{Condition} & \textbf{Gate} & " +
          " & ".join(r"\textbf{%s}" % meth(m) for m in METHODS), rows)

    # ---------------------------------------------------------------- C.2 localisation per condition
    rows = []
    for c in COND:
        d = loc[(loc.gate == 1) & (loc.group == c)].set_index("method")
        rows.append(" & ".join([nm(c)] +
                               ["%.3f" % d.loc[m, "rmse_bins"] for m in METHODS]))
    d = loc[(loc.gate == 1) & (loc.group == "ALL")].set_index("method")
    rows.append(r"\midrule " + " & ".join([r"\textbf{pooled}"] +
                                          [r"\textbf{%.3f}" % d.loc[m, "rmse_bins"]
                                           for m in METHODS]))
    table("Combined localisation RMSE in bins, per condition, at the primary gate. Measured over "
          "each detector's own true positives, so the averages are not taken over identical target "
          "populations --- see Section~\\ref{sec:localization}.",
          "tab:appLoc", "lccccc",
          r"\textbf{Condition} & " + " & ".join(r"\textbf{%s}" % meth(m) for m in METHODS), rows)

    # ---------------------------------------------------------------- C.3 measured Pfa
    rows = []
    for c in sorted(pfa.condition.unique()):
        d = pfa[pfa.condition == c].set_index("method")
        rows.append(" & ".join([nm(c)] +
                               ["%.3f" % d.loc[m, "ratio_to_target"] for m in METHODS]))
    table("Achieved per-cell false-alarm rate as a ratio to the design rate of "
          "$10^{-4}$, per condition and arm, including the target-free noise stratum. "
          "A value of $1.000$ is an exactly matched operating point. This is "
          "Figure~\\ref{fig:oppoint} in numerical form.",
          "tab:appPfa", "lccccc",
          r"\textbf{Condition} & " + " & ".join(r"\textbf{%s}" % meth(m) for m in METHODS), rows)

    # ---------------------------------------------------------------- C.4 robustness gate bootstrap
    rows = []
    for _, r in b3.sort_values("diff", ascending=False).iterrows():
        rows.append(" & ".join([nm(r["condition"]), r["cfar_method"],
                                "%+.4f" % r["diff"],
                                "$[%+.4f,\\ %+.4f]$" % (r["ci_lo"], r["ci_hi"]),
                                "%.3f" % r["p_boot"],
                                "yes" if r["sig (Bonf)"] else "no"]))
    table("The full benchmark at the $\\pm\\ProtocolGateRobust$-bin robustness gate. The main text "
          "reports only the homogeneous-clutter row of this table. Same protocol, same frames, "
          "same \\ProtocolBootstrap{} paired frame resamples, Bonferroni-corrected across "
          "\\SynConditions{} conditions.",
          "tab:appTolThree", "llclcc",
          r"\textbf{Condition} & \textbf{CFAR} & \textbf{Diff.} & "
          r"\textbf{95\,\% CI} & \textbf{$p$} & \textbf{Sig.}", rows)

    # ---------------------------------------------------------------- C.5 CARRADA per sequence
    rows = []
    for s in R1["per_sequence"]:
        rows.append(" & ".join([r"\texttt{%s}" % s["sequence"], "%d" % s["eligible_objects"],
                                "%.4f" % s["tinycnn"], "%.4f" % s["cfar_CA"],
                                "%+.4f" % s["delta"], "%.4f" % s["cfar_GO"],
                                "%.4f" % s["cfar_SO"], "%.4f" % s["cfar_OS"]]))
    bs = R1["paired_bootstrap"]
    table("Exact dense-mask object recall per CARRADA test sequence, for every detector arm. "
          "The sequence-balanced mean difference is $%+.4f$ with a \\SI{95}{\\percent} interval of "
          "$[%+.4f, %+.4f]$ over %d bootstrap resamples. This is the numerical form of the "
          "right-hand panel of Figure~\\ref{fig:r1_primary}."
          % (bs["mean_delta"], bs["ci_lo"], bs["ci_hi"], bs["n_bootstrap"]),
          "tab:appSeq", "lrccccccc",
          r"\textbf{Sequence} & \textbf{$n$} & \textbf{TinyCNN} & \textbf{CA} & "
          r"\textbf{Diff.} & \textbf{GO} & \textbf{SO} & \textbf{OS}", rows)

    # ---------------------------------------------------------------- C.6 CARRADA per seed
    P = R1["primary"]
    seeds = P["tinycnn_per_seed"]
    rows = []
    for k in sorted(seeds, key=int):
        v = seeds[k]
        rows.append(" & ".join([k, "%.4f" % v, "%+.4f" % (v - P["cfar"]["CA"]),
                                "above" if v > P["cfar"]["CA"] else "below"]))
    table("Per-seed exact dense-mask object recall on CARRADA, against the primary classical "
          "comparator's \\RoneCFARCA{}. No seed was selected, dropped or ensembled; the reported "
          "figure is the mean of all \\TinySeeds{}. Standard deviation \\RoneSeedSD{}.",
          "tab:appSeed", "lccc",
          r"\textbf{Seed} & \textbf{Recall} & \textbf{$-$ CA-CFAR} & \textbf{Relative to CA}", rows)

    # ---------------------------------------------------------------- C.7 CARRADA strata detail
    rows = []
    for key, lab in (("by_class", "Class"), ("by_range", "Range block [bins]"),
                     ("by_doppler", "Zero-Doppler")):
        d = R1[key]
        keys = [k for k in d if d[k]["eligible_objects"] > 0]
        if key == "by_range":
            keys = sorted(keys, key=lambda s: int(s.split("-")[0]))
        else:
            keys = sorted(keys)
        rows.append(r"\multicolumn{6}{@{}l}{\emph{%s}}" % lab)
        for k in keys:
            v = d[k]
            rows.append(" & ".join(["\\quad %s" % k.replace("_", " "),
                                    "%d" % v["eligible_objects"],
                                    "%.4f" % v["tinycnn"], "%.4f" % v["cfar_CA"],
                                    "%+.4f" % (v["tinycnn"] - v["cfar_CA"]),
                                    "%.4f" % v["cfar_OS"]]))
    table("Every pre-specified CARRADA test stratum, with its difference column. "
          "Section~\\ref{sec:r7secondary} discusses the range blocks; class comparisons are "
          "confounded by mask size and the cyclist row rests on two sequences only.",
          "tab:appStrata", "lrcccc",
          r"\textbf{Stratum} & \textbf{$n$} & \textbf{TinyCNN} & \textbf{CA-CFAR} & "
          r"\textbf{Diff.} & \textbf{OS-CFAR}", rows)

    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(out) + "\n")
    n = sum(1 for l in out if l.startswith(r"\begin{table}"))
    print("wrote %s  (%d tables)" % (os.path.relpath(OUT, ROOT), n))
    return 0


if __name__ == "__main__":
    sys.exit(main())
