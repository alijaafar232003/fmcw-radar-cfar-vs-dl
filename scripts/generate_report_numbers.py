    macro("RoneSeqTinyCNNLead", sum(1 for s in seq if s["delta"] > 0))
    macro("RoneSeedsAboveCFAR",
          sum(1 for v in P["tinycnn_per_seed"].values() if v > P["cfar"]["CA"]))

