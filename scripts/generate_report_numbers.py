    macro("RzeroCarradaRidge", f(rg["carrada_ridge_peak_over_floor_db"], 1))
    macro("RzeroSimRidge", f(rg["simulator_ridge_peak_over_floor_db"], 1))
    macro("RzeroCarradaRidgeHalf", rg["ridge_half_width_carrada"])
    macro("RzeroSimRidgeHalf", rg["ridge_half_width_simulator"])
    rep = R0["representation"]
    macro("RzeroSlope", f(rep["slope_vs_10log10raw_mean"], 4))
    macro("RzeroSlopeSD", f(rep["slope_vs_10log10raw_sd"], 4))
    macro("RzeroResidual", f(rep["resid_std_db_mean"], 3))

