"""Generate report/numbers.tex — every reportable figure as a LaTeX macro.

The report must never contain a hand-typed result. Each number below is read from the artefact
that produced it, so the prose cannot drift from the data and a changed result propagates on the
next build rather than silently disagreeing with the tables.

Usage:  python scripts/generate_report_numbers.py
"""
from __future__ import annotations

import json
import math
import os
import sys

import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EXP = os.path.join(ROOT, "experiments", "r_carrada_real_data_validation")
OUT = os.path.join(ROOT, "report", "numbers.tex")

lines: list[str] = []


def macro(name: str, value, comment: str = ""):
    """Emit \newcommand{\name}{value}. Names must be letters only (TeX restriction)."""
    assert name.isalpha(), "macro name must be letters only: " + name
    c = "  % " + comment if comment else ""
    lines.append("\\newcommand{{\\{}}}{{{}}}{}".format(name, value, c))


def f(x, nd=3):
    return "{:.{}f}".format(float(x), nd)


def pct(x, nd=1):
    return "{:.{}f}\\%".format(100 * float(x), nd)


def main():
    lines.append("% " + "=" * 74)
    lines.append("% AUTO-GENERATED by scripts/generate_report_numbers.py -- DO NOT EDIT BY HAND.")
    lines.append("% Every value is read from the artefact that produced it.")
    lines.append("% Regenerate after any change to results, then rebuild the report.")
    lines.append("% " + "=" * 74)
    lines.append("")

    # ---------------------------------------------------------------- R1 real-data
    R1 = json.load(open(os.path.join(EXP, "results", "r1_test", "r1_summary.json")))
    P, BS, TOL, BUR = (R1["primary"], R1["paired_bootstrap"], R1["tolerance"],
                       R1["unmatched_burden"])

    lines.append("% ---------- R1: CARRADA zero-shot test result ----------")
    macro("RoneEligibleObjects", "{:,}".format(R1["eligible_test_objects"]))
    macro("RoneTinyCNN", f(P["tinycnn_seed_mean"], 4), "exact dense-mask object recall")
    macro("RoneCFARCA", f(P["cfar"]["CA"], 4), "primary classical comparator")
    macro("RoneCFARGO", f(P["cfar"]["GO"], 4))
    macro("RoneCFARSO", f(P["cfar"]["SO"], 4))
    macro("RoneCFAROS", f(P["cfar"]["OS"], 4))
    macro("RoneDelta", "{:+.4f}".format(BS["mean_delta"]))
    macro("RoneCIlo", "{:+.4f}".format(BS["ci_lo"]))
    macro("RoneCIhi", "{:+.4f}".format(BS["ci_hi"]))
    macro("RoneNseq", BS["n_sequences"])
    macro("RoneSeedSD", f(P["tinycnn_seed_sd"], 4))
    seeds = P["tinycnn_per_seed"]
    macro("RoneSeedMin", f(min(seeds.values()), 4))
    macro("RoneSeedMax", f(max(seeds.values()), 4))
    for k, v in seeds.items():
        macro("RoneSeed" + "ZeroOneTwoThreeFourFiveSixSeven".replace("", "")[0:0] +
              ["Zero", "One", "Two", "Three", "Four", "Five", "Six", "Seven"][int(k)], f(v, 4))

    lines.append("")
    lines.append("% ---------- R1: tolerance ladder ----------")
    for t, nm in ((0, "Exact"), (1, "TolOne"), (3, "TolThree")):
        macro("RoneTinyCNN" + nm, f(TOL["tol{}".format(t)]["tinycnn"], 4))
        macro("RoneCFARCA" + nm, f(TOL["tol{}".format(t)]["cfar_CA"], 4))

    lines.append("")
    lines.append("% ---------- R1: strata ----------")
    dz = R1["by_doppler"]
    macro("RoneNearZeroN", "{:,}".format(dz["near_zero"]["eligible_objects"]))
    macro("RoneNearZeroTinyCNN", f(dz["near_zero"]["tinycnn"], 4))
    macro("RoneNearZeroCFAR", f(dz["near_zero"]["cfar_CA"], 4))
    macro("RoneAwayZeroN", "{:,}".format(dz["away_zero"]["eligible_objects"]))
    macro("RoneAwayZeroTinyCNN", f(dz["away_zero"]["tinycnn"], 4))
    macro("RoneAwayZeroCFAR", f(dz["away_zero"]["cfar_CA"], 4))
    macro("RoneNearZeroFrac",
          pct(dz["near_zero"]["eligible_objects"] / R1["eligible_test_objects"], 0))
    for cls, nm in (("car", "Car"), ("pedestrian", "Ped"), ("cyclist", "Cyc")):
        v = R1["by_class"][cls]
        macro("Rone" + nm + "N", "{:,}".format(v["eligible_objects"]))
        macro("Rone" + nm + "TinyCNN", f(v["tinycnn"], 4))
        macro("Rone" + nm + "CFAR", f(v["cfar_CA"], 4))

    lines.append("")
    lines.append("% ---------- R1: unmatched-detection burden (NOT Pfa) ----------")
    macro("RoneBurdenTinyCNN", f(BUR["TinyCNN"]["mean"], 2))
    macro("RoneBurdenCFARCA", f(BUR["CFAR-CA"]["mean"], 2))

    # ---------------------------------------------------------------- R0 domain audit
    R0 = json.load(open(os.path.join(EXP, "results", "r0_audit.json")))
    bc, bs, rg = R0["background_carrada"], R0["background_simulator"], R0["ridge"]
    lines.append("")
    lines.append("% ---------- R0: domain audit ----------")
    for key, nm in (("cv", "CV"), ("gamma_k_moment", "GammaK"), ("db_std", "DBstd"),
                    ("lag1_range", "LagRange"), ("lag1_doppler", "LagDoppler")):
        macro("RzeroCarrada" + nm, f(bc[key]["mean"], 3))
        macro("RzeroCarrada" + nm + "SE", f(bc[key]["se"], 3))
        macro("RzeroSim" + nm, f(bs[key]["mean"], 3))
        macro("RzeroSim" + nm + "SE", f(bs[key]["se"], 3))
    macro("RzeroCarradaRidge", f(rg["carrada_ridge_peak_over_floor_db"], 1))
    macro("RzeroSimRidge", f(rg["simulator_ridge_peak_over_floor_db"], 1))
    macro("RzeroCarradaRidgeHalf", rg["ridge_half_width_carrada"])
    macro("RzeroSimRidgeHalf", rg["ridge_half_width_simulator"])
    rep = R0["representation"]
    macro("RzeroSlope", f(rep["slope_vs_10log10raw_mean"], 4))
    macro("RzeroSlopeSD", f(rep["slope_vs_10log10raw_sd"], 4))
    macro("RzeroResidual", f(rep["resid_std_db_mean"], 3))

    # ---------------------------------------------------------------- dataset counts
    P1 = json.load(open(os.path.join(EXP, "results", "phase1_dataset_verification.json")))
    t = P1["terminology"]
    lines.append("")
    lines.append("% ---------- CARRADA dataset ----------")
    macro("CarradaSequences", P1["n_sequences_on_disk"])
    macro("CarradaFrames", "{:,}".format(t["total frames (light list)"]))
    macro("CarradaAnnotatedFrames", "{:,}".format(t["annotated frames"]))
    macro("CarradaEmptyFrames", "{:,}".format(t["empty frames"]))
    macro("CarradaObjectFrames", "{:,}".format(t["frame-level object instances"]))
    macro("CarradaTracks", t["unique tracks (frame-oriented)"])
    for sp, nm in (("Train", "Train"), ("Validation", "Val"), ("Test", "Test")):
        s = P1["official_splits"][sp]
        macro("Carrada" + nm + "Seq", s["n_sequences"])
        macro("Carrada" + nm + "Frames", "{:,}".format(s["frames"]))
        macro("Carrada" + nm + "Objects", "{:,}".format(s["object_frames"]))

    # ---------------------------------------------------------------- synthetic headline
    syn = pd.read_csv(os.path.join(ROOT, "results", "dl",
                                   "bootstrap_frozen_ep021_test_tol1.csv"))
    lines.append("")
    lines.append("% ---------- frozen synthetic benchmark (bench2_test, epoch 21) ----------")
    macro("SynConditions", len(syn))
    macro("SynWins", int(((syn["diff"] > 0) & syn["sig (Bonf)"]).sum()))
    words = {"clutter_edge": "ClutterEdge", "clutter": "Clutter", "isolated": "Isolated",
             "masking": "Masking", "mixed": "Mixed", "multi": "Multi",
             "unresolved": "Unresolved"}
    for _, r in syn.iterrows():
        nm = words[r["condition"]]
        macro("Syn" + nm + "DL", f(r["dl_pd"], 4))
        macro("Syn" + nm + "CFAR", f(r["cfar_pd"], 4))
        macro("Syn" + nm + "Diff", "{:+.4f}".format(r["diff"]))
        macro("Syn" + nm + "Method", r["cfar_method"])

    # ---------------------------------------------------------------- Chapter 3: radar + datasets
    # Read from src/radar/config.py so the report cannot drift from the simulator.
    sys.path.insert(0, os.path.join(ROOT, "src"))
    from radar.config import RadarConfig, derive_radar_params            # noqa: E402
    from radar.calibration import snr_processing_gain_db                 # noqa: E402

    rc = RadarConfig()
    rd = derive_radar_params(rc)

    lines.append("")
    lines.append("% ---------- Chapter 3: sensor specification ----------")
    macro("RadarFc", "{:.0f}".format(rc.fc / 1e9))
    macro("RadarB", "{:.0f}".format(rc.B / 1e6))
    macro("RadarTc", "{:.1f}".format(rc.Tc * 1e6))
    macro("RadarN", rc.N)
    macro("RadarM", rc.M)
    macro("RadarRangeBins", rc.N // 2)
    macro("RadarLambda", "{:.4f}".format(rd.lambda_m * 1e3))
    macro("RadarSlope", "{:.4f}".format(rd.slope / 1e12))
    macro("RadarFs", "{:.4f}".format(rd.fs / 1e6))
    macro("RadarRangeRes", "{:.4f}".format(rd.range_res))
    macro("RadarRangeMax", "{:.2f}".format(rd.range_max))
    macro("RadarVelRes", "{:.4f}".format(rd.vel_res))
    macro("RadarVelMax", "{:.2f}".format(rd.vel_max))
    macro("RadarFrameTime", "{:.4f}".format(rc.M * rc.Tc * 1e3))
    macro("RadarCoherentGain", "{:.2f}".format(10.0 * math.log10(rc.N * rc.M)))
    macro("RadarProcGain", "{:.2f}".format(snr_processing_gain_db(rc)))
    # The effective bandwidth implied by CARRADA's own bin geometry (Chapter 3 derivation).
    macro("CarradaBeff", "{:.0f}".format(
        2.998e8 * (rc.N // 2) / (2.0 * 50.0) / 1e6))
    macro("CarradaQuotedB", "4")
    macro("CarradaBinSpacing", "{:.3f}".format(50.0 / (rc.N // 2)))

    lines.append("")
    lines.append("% ---------- Chapter 3: dataset splits ----------")
    for split in ("train", "val", "tune", "test", "snr_sweep"):
        d = os.path.join(ROOT, "data", "bench2_" + split, "frames")
        n = len(os.listdir(d)) if os.path.isdir(d) else 0
        nm = "".join(w.capitalize() for w in split.split("_"))
        macro("Bench" + nm + "Frames", "{:,}".format(n))

    # ---------------------------------------------------------------- Pd-vs-SNR (dB currency)
    # The literature reports learned-vs-CFAR margins in dB of SNR at Pd 0.5.
    # Recomputed here from the frozen sweep artefact so the report never quotes a log.
    sweep = pd.read_csv(os.path.join(ROOT, "results", "dl",
                                     "pd_vs_snr_frozen_ep021.csv"))

    def _snr50(sub):
        sub = sub.sort_values("snr")
        x, y = sub["snr"].to_numpy(), sub["pd"].to_numpy()
        for i in range(1, len(y)):
            if y[i - 1] < 0.5 <= y[i]:
                return x[i - 1] + (0.5 - y[i - 1]) * (x[i] - x[i - 1]) / (y[i] - y[i - 1])
        return float("nan")

    PFA = 1e-4
    # Clairvoyant single-cell square-law bound: Pd = Pfa^(1/(1+SNR)); set Pd = 0.5.
    theory = 10.0 * math.log10(math.log(PFA) / math.log(0.5) - 1.0)

    lines.append("")
    lines.append("% ---------- Pd vs cell SNR, frozen ep021, matched measured Pfa 1e-4 ----------")
    macro("SynSnrTheory", "{:.2f}".format(theory))
    for m in ("CA", "GO", "OS", "SO", "DL"):
        g1 = sweep[(sweep.gate == 1) & (sweep.method == m)]
        g0 = sweep[(sweep.gate == 0) & (sweep.method == m)]
        macro("SynSnrFifty" + m, "{:.2f}".format(_snr50(g1)))
        v0 = _snr50(g0)
        macro("SynSnrFiftyExact" + m,
              "n/a" if math.isnan(v0) else "{:.2f}".format(v0))
        macro("SynPdMaxExact" + m, "{:.3f}".format(float(g0["pd"].max())))
    ca1 = _snr50(sweep[(sweep.gate == 1) & (sweep.method == "CA")])
    dl1 = _snr50(sweep[(sweep.gate == 1) & (sweep.method == "DL")])
    ca0 = _snr50(sweep[(sweep.gate == 0) & (sweep.method == "CA")])
    macro("SynSnrGainDL", "{:.2f}".format(ca1 - dl1))
    macro("SynCfarLossCA", "{:.2f}".format(ca0 - theory))

    # ---------------------------------------------------------------- range blocks
    lines.append("")
    lines.append("% ---------- R1: range-stratified (R0 blocks) ----------")
    words = {"10-60": "A", "60-110": "B", "110-160": "C", "160-210": "D", "210-246": "E"}
    for blk, w in words.items():
        v = R1["by_range"].get(blk)
        if not v:
            continue
        macro("RoneRange" + w + "Label", blk.replace("-", "--"))
        macro("RoneRange" + w + "N", "{:,}".format(v["eligible_objects"]))
        macro("RoneRange" + w + "TinyCNN", f(v["tinycnn"], 4))
        macro("RoneRange" + w + "CFAR", f(v["cfar_CA"], 4))

    # ---------------------------------------------------------------- multi-peak
    try:
        import pandas as _pd
        mp = _pd.read_csv(os.path.join(EXP, "results", "r1_test", "multipeak_test.csv"))
        lines.append("")
        lines.append("% ---------- R1: extended-object multi-peak diagnostic ----------")
        for lab, sub in (("TinyCNN", mp[mp.detector == "tinycnn"]),
                         ("CFARCA", mp[(mp.detector == "cfar") & (mp.cfar_kind == "CA")])):
            v = sub["peaks_inside_support"].to_numpy()
            macro("RoneMultiPeak" + lab,
                  "{:.1f}\%".format(100.0 * float((v >= 2).mean())))
    except Exception:
        pass

    # ---------------------------------------------------------------- provenance
    FR = json.load(open(os.path.join(EXP, "results", "preregistration_freeze.json")))
    lines.append("")
    lines.append("% ---------- provenance ----------")
    macro("PrereghashShort", FR["sha256"][:16])
    macro("Prereghash", FR["sha256"])

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    n = sum(1 for l in lines if l.startswith("\\newcommand"))
    print("wrote {}  ({} macros)".format(os.path.relpath(OUT, ROOT), n))
    return 0


if __name__ == "__main__":
    sys.exit(main())
