    rd = derive_radar_params(rc)

    lines.append("")
    lines.append("% ---------- Chapter 3: sensor specification ----------")
    macro("RadarFc", "{:.0f}".format(rc.fc / 1e9))
    macro("RadarB", "{:.0f}".format(rc.B / 1e6))
    macro("RadarTc", "{:.1f}".format(rc.Tc * 1e6))
    macro("RadarN", rc.N)
    macro("RadarM", rc.M)
    macro("RadarRangeBins", rc.N // 2)
    macro("RadarLambda", "{:.4f}".format(rd.lambda_m * 1e3))
    macro("RadarSlope", "{:.4f}".format(rd.slope / 1e12))
    macro("RadarFs", "{:.4f}".format(rd.fs / 1e6))
    macro("RadarRangeRes", "{:.4f}".format(rd.range_res))
    macro("RadarRangeMax", "{:.2f}".format(rd.range_max))
    macro("RadarVelRes", "{:.4f}".format(rd.vel_res))
    macro("RadarVelMax", "{:.2f}".format(rd.vel_max))
    macro("RadarFrameTime", "{:.4f}".format(rc.M * rc.Tc * 1e3))
    macro("RadarCoherentGain", "{:.2f}".format(10.0 * math.log10(rc.N * rc.M)))
    macro("RadarProcGain", "{:.2f}".format(snr_processing_gain_db(rc)))
    # The effective bandwidth implied by CARRADA's own bin geometry (Chapter 3 derivation).
    macro("CarradaBeff", "{:.0f}".format(
        2.998e8 * (rc.N // 2) / (2.0 * 50.0) / 1e6))
    macro("CarradaQuotedB", "4")
    macro("CarradaBinSpacing", "{:.3f}".format(50.0 / (rc.N // 2)))

    lines.append("")
    lines.append("% ---------- Chapter 3: dataset splits ----------")
    for split in ("train", "val", "tune", "test", "snr_sweep"):
        d = os.path.join(ROOT, "data", "bench2_" + split, "frames")
        n = len(os.listdir(d)) if os.path.isdir(d) else 0
        nm = "".join(w.capitalize() for w in split.split("_"))
        macro("Bench" + nm + "Frames", "{:,}".format(n))

    # ---------------------------------------------------------------- Chapter 4: detectors
    # Window geometry and alphas from the artefacts that define them, model facts from the
    # frozen contract, so the chapter cannot drift from what was actually run.
    import yaml                                                          # noqa: E402
    fz = yaml.safe_load(open(os.path.join(ROOT, "configs", "frozen_dl.yaml"), encoding="utf-8"))
    at = json.load(open(os.path.join(ROOT, "configs", "cfar_alpha_table.json"), encoding="utf-8"))

    gr, tr = fz["cfar"]["guard"], fz["cfar"]["train"]
    gd, td = fz["cfar"]["guard_v"], fz["cfar"]["train_v"]
    win_r, win_d = 1 + 2 * (gr + tr), 1 + 2 * (gd + td)
    n_guard = (1 + 2 * gr) * (1 + 2 * gd) - 1
    n_ref = win_r * win_d - n_guard - 1

    lines.append("")
    lines.append("% ---------- Chapter 4: CFAR window and calibrated multipliers ----------")
    macro("CfarWinR", win_r)
    macro("CfarWinD", win_d)
    macro("CfarWinCells", win_r * win_d)
    macro("CfarGuardR", gr)
    macro("CfarTrainR", tr)
    macro("CfarGuardD", gd)
    macro("CfarTrainD", td)
    macro("CfarNGuard", n_guard)
    macro("CfarNRef", n_ref)
    macro("CfarOsRank", "{:.2f}".format(fz["cfar"]["os_rank_frac"]))
    for k, v in at["entries"].items():
        macro("CfarAlpha" + k.split("|")[0], "{:.4f}".format(v))
    # The "analytic reference": equation (2.x) evaluated with each statistic's cell count.
    # Exact for CA; half-ring approximation for GO/SO; first approximation only for OS.
    # Read from the audit artefact, which is what the figure plots.
    aud = pd.read_csv(os.path.join(ROOT, "results", "cfar_alpha_audit.csv"))
    for _, r in aud.iterrows():
        macro("CfarAlpha" + str(r["method"]) + "Analytic",
              "{:.4f}".format(float(r["alpha_closed_form"])))
        macro("CfarPfaAtAnalytic" + str(r["method"]),
              "{:.2e}".format(float(r["pfa_cells_verifyseed_at_current"])))

    lines.append("")
    lines.append("% ---------- Chapter 4: frozen network ----------")
    macro("TinyParams", "{:,}".format(fz["model"]["params"]))
    macro("TinyWidth", fz["model"]["width"])
    macro("TinyRFR", fz["model"]["receptive_field"][0])
    macro("TinyRFD", fz["model"]["receptive_field"][1])
    macro("TinyDilR", ", ".join(str(d) for d in fz["model"]["dilations_range"]))
    macro("TinyDilD", ", ".join(str(d) for d in fz["model"]["dilations_doppler"]))
    macro("TinyEpochs", fz["training"]["epochs"])
    macro("TinyPosWeight", "{:.0f}".format(fz["training"]["pos_weight"]))
    macro("TinyLR", fz["training"]["lr"])
    macro("TinyBatch", fz["training"]["batch_size"])
    macro("TinySeeds", len(fz["training"]["seeds"]))
    macro("TinyThreads", fz["training"]["threads"])
    # The suppression radius is the ONE evaluation field that comes from the revised protocol
    # rather than from the frozen contract. Both are emitted: the report uses \ProtocolNms
    # throughout and names \ProtocolNmsOriginal only in the provenance appendix.
    macro("ProtocolNms", R)
    macro("ProtocolNmsWin", 2 * R + 1)
    macro("ProtocolNmsOriginal", fz["evaluation"]["nms_size"])
    macro("ProtocolNmsOriginalWin", 2 * int(fz["evaluation"]["nms_size"]) + 1)
    macro("ProtocolGate", fz["evaluation"]["gate"])
    macro("ProtocolGateRobust", fz["evaluation"]["gate_robustness"])
    macro("ProtocolBootstrap", "{:,}".format(fz["evaluation"]["n_bootstrap"]))
    macro("ProtocolPfa", "{:.0e}".format(fz["evaluation"]["target_pfa"]).replace("e-04", "^{-4}"))
    macro("ProtocolBonf", "{:.4f}".format(0.05 / 7))

    # ---------------------------------------------------------------- NMS radius selection
    # Development-set sweep behind Section "Selecting the suppression radius". Confirmation split
    # only; the tuning split agrees on every gate and is not quoted separately.
    nms = pd.read_csv(os.path.join(E6, "results", "p1_selection",
                                   "nms_selection_sweep_val.csv"))
    lines.append("")
    lines.append("% ---------- NMS radius selection (development data only) ----------")
    _nz = nms[nms.condition == "noise"].set_index("nms")
    macro("NmsCandOne", "{:.0f}".format(_nz.loc[1, "cand_per_frame_CA"]))
    macro("NmsCandFive", "{:.0f}".format(_nz.loc[5, "cand_per_frame_CA"]))
    macro("NmsCandRatio", "{:.1f}".format(_nz.loc[1, "cand_per_frame_CA"]
                                          / _nz.loc[5, "cand_per_frame_CA"]))
    _iso = nms[(nms.condition == "isolated") & (nms.method == "DL")]["pd"]
    macro("NmsIsolatedSpread", f(_iso.max() - _iso.min(), 3))
    _mask = nms[(nms.condition == "masking") & (nms.method == "DL")].set_index("nms")["pd"]
    macro("NmsMaskingOne", f(_mask.loc[1], 3))
    macro("NmsMaskingFive", f(_mask.loc[5], 3))
    _unr = nms[(nms.condition == "unresolved") & (nms.method == "DL")].set_index("nms")
    macro("NmsUnresolvedOne", f(_unr.loc[1, "pd"], 4))
    # Duplicate in-gate detections at radius 1, across the scored conditions, for the network;
    # and the maximum over EVERY arm and condition at the larger radii, which is exactly zero.
    _dup = nms[(nms.nms == 1) & (nms.method == "DL")]["frac_truths_two_plus"].dropna()
    macro("NmsDupOneMin", pct(_dup.min(), 0))
    macro("NmsDupOneMax", pct(_dup.max(), 0))
    macro("NmsDupOneCFAR", pct(nms[(nms.nms == 1) & (nms.method != "DL")]
                               ["frac_truths_two_plus"].dropna().max(), 0))
    macro("NmsDupOther", pct(nms[nms.nms > 1]["frac_truths_two_plus"].dropna().max(), 1))
    macro("NmsRadiiTested", ", ".join(str(int(v)) for v in sorted(nms.nms.unique())))

    # ---------------------------------------------------------------- Pd-vs-SNR (dB currency)
    # The literature reports learned-vs-CFAR margins in dB of SNR at Pd 0.5.
    # Recomputed here from the frozen sweep artefact so the report never quotes a log.
    sweep = pd.read_csv(os.path.join(FINAL, "pd_vs_snr_final_r{}.csv".format(R)))

    def _snr50(sub):
        sub = sub.sort_values("snr")
        x, y = sub["snr"].to_numpy(), sub["pd"].to_numpy()
        for i in range(1, len(y)):
            if y[i - 1] < 0.5 <= y[i]:
                return x[i - 1] + (0.5 - y[i - 1]) * (x[i] - x[i - 1]) / (y[i] - y[i - 1])
        return float("nan")

    PFA = 1e-4
    # Clairvoyant single-cell square-law bound: Pd = Pfa^(1/(1+SNR)); set Pd = 0.5.
    theory = 10.0 * math.log10(math.log(PFA) / math.log(0.5) - 1.0)

    lines.append("")
    lines.append("% ---------- Pd vs cell SNR, frozen ep021, matched measured Pfa 1e-4 ----------")
    macro("SynSnrTheory", "{:.2f}".format(theory))
    for m in ("CA", "GO", "OS", "SO", "DL"):
        g1 = sweep[(sweep.gate == 1) & (sweep.method == m)]
        g0 = sweep[(sweep.gate == 0) & (sweep.method == m)]
        macro("SynSnrFifty" + m, "{:.2f}".format(_snr50(g1)))
        v0 = _snr50(g0)
        macro("SynSnrFiftyExact" + m,
              "n/a" if math.isnan(v0) else "{:.2f}".format(v0))
        macro("SynPdMaxExact" + m, "{:.3f}".format(float(g0["pd"].max())))
    ca1 = _snr50(sweep[(sweep.gate == 1) & (sweep.method == "CA")])
    dl1 = _snr50(sweep[(sweep.gate == 1) & (sweep.method == "DL")])
    ca0 = _snr50(sweep[(sweep.gate == 0) & (sweep.method == "CA")])
    macro("SynSnrGainDL", "{:.2f}".format(ca1 - dl1))
    macro("SynCfarLossCA", "{:.2f}".format(ca0 - theory))

    # ---------------------------------------------------------------- Chapter 5: tolerance ladder
    syn3 = pd.read_csv(os.path.join(FINAL, "bootstrap_final_r{}_tol3.csv".format(R)))
    lines.append("")
    lines.append("% ---------- Chapter 5: same benchmark at the +/-3 bin gate ----------")
    macro("SynWinsTolThree", int(((syn3["diff"] > 0) & syn3["sig (Bonf)"]).sum()))
    words3 = {"clutter_edge": "ClutterEdge", "clutter": "Clutter", "isolated": "Isolated",
              "masking": "Masking", "mixed": "Mixed", "multi": "Multi",
              "unresolved": "Unresolved"}
    for _, r in syn3.iterrows():
        nm = words3[r["condition"]]
        macro("SynTolThree" + nm + "DL", f(r["dl_pd"], 4))
        macro("SynTolThree" + nm + "CFAR", f(r["cfar_pd"], 4))
        macro("SynTolThree" + nm + "Diff", "{:+.4f}".format(r["diff"]))
    # Confidence interval on the one condition where the classical arm leads.
    cl = syn3[syn3.condition == "clutter"].iloc[0]
    macro("SynTolThreeClutterCIlo", f(cl["ci_lo"], 4))
    macro("SynTolThreeClutterCIhi", f(cl["ci_hi"], 4))
    macro("SynTolThreeClutterP", "{:.3f}".format(float(cl["p_boot"])))
    # \SynClutterP is already emitted by the per-condition loop above, together with every other
    # condition's p-value; emitting it again here would redefine it and stop the build.

    # ---------------------------------------------------------------- Chapter 5: localization
    loc = pd.read_csv(os.path.join(FINAL, "localization_final_r{}.csv".format(R)))
    a = loc[(loc.gate == 1) & (loc.group == "ALL")].set_index("method")
    lines.append("")
    lines.append("% ---------- Chapter 5: localization, all conditions pooled ----------")
    for m in ("CA", "DL"):
        tag = "CA" if m == "CA" else "DL"
        macro("LocRmse" + tag, f(a.loc[m, "rmse_bins"], 3))
        macro("LocDr" + tag, f(a.loc[m, "dr_bins"], 3))
        macro("LocDv" + tag, f(a.loc[m, "dv_bins"], 3))
        macro("LocRangeM" + tag, f(a.loc[m, "range_m"], 3))
        macro("LocVelMps" + tag, f(a.loc[m, "vel_mps"], 3))
    macro("LocRmseRatio", "{:.2f}".format(a.loc["DL", "rmse_bins"] / a.loc["CA", "rmse_bins"]))
    macro("LocDvRatio", "{:.1f}".format(a.loc["DL", "dv_bins"] / a.loc["CA", "dv_bins"]))
    cf = a.drop("DL")["rmse_bins"]
    macro("LocRmseCFARMin", f(cf.min(), 3))
    macro("LocRmseCFARMax", f(cf.max(), 3))

    # ---------------------------------------------------------------- Chapter 5: runtime and Pfa
    rt = pd.read_csv(os.path.join(ROOT, "results", "dl",
                                  "runtime_cost_frozen_ep021_test.csv")).set_index("method")
    lines.append("")
    lines.append("% ---------- Chapter 5: cost and achieved operating point ----------")
    macro("RuntimeDL", f(rt.loc["DL (TinyCNN)", "ms_per_frame"], 2))
    macro("RuntimeCA", f(rt.loc["CA-CFAR", "ms_per_frame"], 2))
    macro("RuntimeGO", f(rt.loc["GO-CFAR", "ms_per_frame"], 2))
    macro("RuntimeSO", f(rt.loc["SO-CFAR", "ms_per_frame"], 2))
    macro("RuntimeOS", f(rt.loc["OS-CFAR", "ms_per_frame"], 2))
    macro("RuntimeMMac", f(rt.loc["DL (TinyCNN)", "mmac_per_frame"], 1))
    macro("RuntimeDLoverCA",
          "{:.1f}".format(rt.loc["DL (TinyCNN)", "ms_per_frame"] / rt.loc["CA-CFAR",
                                                                          "ms_per_frame"]))
    macro("RuntimeOSoverDL",
          "{:.1f}".format(rt.loc["OS-CFAR", "ms_per_frame"] / rt.loc["DL (TinyCNN)",
                                                                     "ms_per_frame"]))
    pf = pd.read_csv(os.path.join(FINAL, "measured_pfa_final_r{}_tol1.csv".format(R)))
    macro("PfaRatioMin", f(pf["ratio_to_target"].min(), 3))
    macro("PfaRatioMax", f(pf["ratio_to_target"].max(), 3))

    # ---------------------------------------------------------------- range blocks
    lines.append("")
    lines.append("% ---------- R1: range-stratified (R0 blocks) ----------")
    words = {"10-60": "A", "60-110": "B", "110-160": "C", "160-210": "D", "210-246": "E"}
    for blk, w in words.items():
        v = R1["by_range"].get(blk)
        if not v:
            continue
        macro("RoneRange" + w + "Label", blk.replace("-", "--"))
        macro("RoneRange" + w + "N", "{:,}".format(v["eligible_objects"]))
        macro("RoneRange" + w + "TinyCNN", f(v["tinycnn"], 4))
        macro("RoneRange" + w + "CFAR", f(v["cfar_CA"], 4))
        macro("RoneRange" + w + "Diff", "{:+.4f}".format(v["tinycnn"] - v["cfar_CA"]))

    # ---------------------------------------------------------------- multi-peak
    try:
        import pandas as _pd
        mp = _pd.read_csv(os.path.join(EXP, "results", "r1_test", "multipeak_test.csv"))
        lines.append("")
        lines.append("% ---------- R1: extended-object multi-peak diagnostic ----------")
        for lab, sub in (("TinyCNN", mp[mp.detector == "tinycnn"]),
                         ("CFARCA", mp[(mp.detector == "cfar") & (mp.cfar_kind == "CA")])):
            v = sub["peaks_inside_support"].to_numpy()
            macro("RoneMultiPeak" + lab,
                  "{:.1f}\%".format(100.0 * float((v >= 2).mean())))
    except Exception:
        pass

    # ---------------------------------------------------------------- Chapter 6: attribution
    # E2, E3 and E4 were first analysed at the superseded suppression radius. They were re-scored
    # at the final radius before submission, from the SAME frozen checkpoints -- no model was
    # retrained -- and every value below is read from those radius-2 artefacts. The originals keep
    # their radius-5 values in `experiments/{integrated_cfar,label_ablation,e4_cut_guard_mask}/`
    # and are not read here; Appendix B records the revision.
    ATT = os.path.join(E6, "results", "p10_attribution")
    ICF = os.path.join(ATT, "e2")
    LAB = os.path.join(ATT, "e3")
    E4R = os.path.join(ATT, "e4")

    lines.append("")
    lines.append("% ---------- E2: integrated CFAR (bench2_val, radius 2) ----------")
    cap = pd.read_csv(os.path.join(ICF, "psf_energy_capture.csv")).set_index("region")
    for reg, nm in (("1x1", "One"), ("3x3", "Three"), ("5x5", "Five")):
        macro("EtwoCap" + nm, pct(cap.loc[reg, "energy_fraction"], 1))
    d2 = pd.read_csv(os.path.join(ICF, "deltas.csv"))
    d2 = d2[d2.gate == 1]
    macro("EtwoConds", int(len(d2[d2.statistic == "uniform"])))
    for st, nm in (("uniform", "Uniform"), ("psf", "Psf")):
        x = d2[d2.statistic == st]
        macro("EtwoDelta" + nm, "{:+.4f}".format(x.delta_integration.mean()))
        macro("EtwoNeg" + nm, int((x.delta_integration < 0).sum()))
        macro("EtwoSig" + nm, int(x.sig_integration.sum()))
    # Doppler error, averaged over the seven scored conditions at the primary gate.
    l2 = pd.read_csv(os.path.join(ICF, "localization.csv"))
    l2 = l2[l2.gate == 1]
    base = l2[l2.arm == "CFAR-CA"].dv_bins.mean()
    for arm, nm in (("INT-psf-CA", "Psf"), ("INT-uniform-CA", "Uniform")):
        macro("EtwoDvRatio" + nm, "{:.2f}".format(l2[l2.arm == arm].dv_bins.mean() / base))

    lines.append("")
    lines.append("% ---------- E3: label ablation (bench2_val, radius 2) ----------")
    ec = pd.read_csv(os.path.join(LAB, "epoch_curve.csv"))
    arms = (("flat3x3", "Flat"), ("gaussian", "Gauss"), ("point", "Point"))
    g1 = ec[(ec.gate == 1) & (ec.epoch == 21)].set_index("arm")
    g0 = ec[(ec.gate == 0) & (ec.epoch == 21)].set_index("arm")
    for arm, nm in arms:
        macro("Ethree" + nm + "Dv", f(g1.loc[arm, "dv_bins"], 4))
        macro("Ethree" + nm + "Dr", f(g1.loc[arm, "dr_bins"], 4))
        macro("Ethree" + nm + "Pd", f(g1.loc[arm, "pd"], 4))
        macro("Ethree" + nm + "GateZero", f(g0.loc[arm, "pd"], 4))
        s = ec[(ec.gate == 1) & (ec.arm == arm)].set_index("epoch")["dv_bins"]
        macro("Ethree" + nm + "Growth", "{:.2f}".format(s.loc[21] / s.loc[5]))
    for arm, nm in (("gaussian", "Gauss"), ("point", "Point")):
        macro("Ethree" + nm + "DeltaPd",
              "{:+.4f}".format(g1.loc[arm, "pd"] - g1.loc["flat3x3", "pd"]))
    macro("EthreeFlatDvRatio",
          "{:.2f}".format(g1.loc["flat3x3", "dv_bins"] / g1.loc["point", "dv_bins"]))
    # The point label's primary-gate cost, as a magnitude, so the prose can say "costs X" without
    # a sign that contradicts the verb. Its per-condition breakdown is not one-sided: the deficit
    # sits in the clutter-bearing conditions, and the point label significantly WINS on the two
    # resolution-limited ones, so both counts are reported.
    d3 = pd.read_csv(os.path.join(LAB, "deltas.csv"))
    p3 = d3[(d3.gate == 1) & (d3.arm == "point")]
    macro("EthreePointPdGap", f(abs(g1.loc["point", "pd"] - g1.loc["flat3x3", "pd"]), 4))
    macro("EthreePointWorseConds", int(((p3.delta < 0) & p3.sig).sum()))
    macro("EthreePointBetterConds", int(((p3.delta > 0) & p3.sig).sum()))
    macro("EthreeConds", int(len(p3)))

    lines.append("")
    lines.append("% ---------- E4: guard-masked patch network (bench2_val, radius 2) ----------")
    d4 = pd.read_csv(os.path.join(E4R, "deltas.csv"))
    for gt, nm in ((1, "One"), (0, "Zero")):
        x = d4[d4.gate == gt]
        macro("EfourDelta" + nm, "{:+.4f}".format(x.delta_pd.mean()))
        macro("EfourPos" + nm, int((x.delta_pd > 0).sum()))
        macro("EfourSig" + nm, int(x.sig.sum()))
        macro("EfourN" + nm, int(len(x)))
    p4 = pd.read_csv(os.path.join(E4R, "per_condition.csv"))
    iso = p4[(p4.gate == 0) & (p4.condition == "isolated")].set_index("arm")
    macro("EfourIsoUnmasked", f(iso.loc["unmasked", "pd"], 3))
    macro("EfourIsoMasked", f(iso.loc["masked", "pd"], 3))

    # ---------------------------------------------------------------- provenance
    FR = json.load(open(os.path.join(EXP, "results", "preregistration_freeze.json")))
    lines.append("")
    lines.append("% ---------- provenance ----------")
    macro("PrereghashShort", FR["sha256"][:16])
    macro("Prereghash", FR["sha256"])
    # The full hash is 64 characters and will not fit a table cell, so it is also emitted in two
    # halves for a two-line presentation. Both halves together are the hash, unaltered.
    macro("PreregHashA", FR["sha256"][:32])
    macro("PreregHashB", FR["sha256"][32:])
    # Long path in a table cell: allow a break after each separator, or it overflows the column.
    macro("PreregFile",
          FR["file"].replace("_", "\\_").replace("/", "/\\allowbreak "))
    macro("PreregBytes", "{:,}".format(FR["size_bytes"]))
    macro("PreregFrozen", FR["frozen_utc"][:10])
    macro("PreregStatus", FR["freeze_status"])
    macro("PreregDraftHashShort", FR["supersedes_draft_sha256"][:16])
    macro("PreregRzeroCommit", FR["r0_baseline_commit"][:7])
    macro("PreregScored", "yes" if FR["detector_scoring_performed"] else "no")
    macro("PreregCarradaUsed", "yes" if FR["carrada_labels_used_for_any_choice"] else "no")

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    n = sum(1 for l in lines if l.startswith("\\newcommand"))
    print("wrote {}  ({} macros)".format(os.path.relpath(OUT, ROOT), n))
    return 0


