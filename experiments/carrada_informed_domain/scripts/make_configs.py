"""Derive the CARRADA-informed dataset configs FROM the frozen original. Phase 4, step 3.

The scenario list -- target counts, placement, separations, amplitude ranges, the SNR sweep, the
strata and their proportions -- must be identical to the original training domain, because the
whole experiment rests on the background being the only thing that changed. Hand-copying a 150-line
YAML is how that guarantee quietly breaks, so the configs are generated by loading
`configs/bench2_train.yaml` and replacing ONLY the `dataset` block and the `save` block.

The diff is asserted afterwards: every top-level key except `dataset` and `save` must compare equal
to the original, and the assertion is what the freeze record cites.

    python make_configs.py

Writes experiments/carrada_informed_domain/configs/{pilot,train,val}.yaml
"""
from __future__ import annotations

import copy
import json
import os
import sys

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
EXP = os.path.dirname(HERE)
ROOT = os.path.dirname(os.path.dirname(EXP))
CFGDIR = os.path.join(EXP, "configs")

SRC_TRAIN = os.path.join(ROOT, "configs", "bench2_train.yaml")
SRC_VAL = os.path.join(ROOT, "configs", "bench2_val.yaml")

# Dataset seeds. Chosen to be far from every seed already used in the project
# (92001 train, 92002-ish val, 96001 the NMS-audit holdout) so a collision is impossible.
SEEDS = {"pilot": 770100, "train": 770001, "val": 770002}
FRAMES = {"pilot": 700, "train": 8400, "val": 1600}

HEADER = """# CARRADA-INFORMED SYNTHETIC DOMAIN -- {name}
#
# AUTO-GENERATED by experiments/carrada_informed_domain/scripts/make_configs.py from
# {src}
# Do not hand-edit: regenerate instead.
#
# Every target-side field -- the scenario list, target counts, placement, separations, amplitude
# ranges, the snr_db sweep, propagation, the strata and their equal proportions -- is copied
# VERBATIM from the original config. Only the `dataset` block (name, frame count, seed) and the
# `save` block differ.
#
# The BACKGROUND is what changes, and it does not live in this file. It is applied by
# scripts/carrada_sim.py, which patches candidate background synthesis into the frozen
# generator: multi-look averaging, the train-derived range profile, and a narrow zero-Doppler
# ridge in essentially every frame. The `scene.clutter` blocks below are inherited from the
# original and are IGNORED by that path -- the ridge model replaces them wholesale. They are
# left in place so the diff against the original stays minimal and auditable.
#
# save.complex is false, deliberately. A multi-look magnitude map is an incoherent power average
# and has no single complex counterpart; writing one look's complex map beside it would invite
# someone to treat the two as the same measurement.
"""


def build(kind, src_path):
    base = yaml.safe_load(open(src_path, encoding="utf-8"))
    out = copy.deepcopy(base)
    out["dataset"] = {
        "name": "carrada_informed_" + kind,
        "description": ("CARRADA-informed background domain, %s split. Targets and strata "
                        "identical to bench2; background multi-look + range profile + narrow "
                        "ridge, calibrated from CARRADA TRAIN only." % kind),
        "output_root": "data",
        "num_frames": FRAMES[kind],
        "random_seed": SEEDS[kind],
    }
    out["save"] = {"compact": True, "preview_png": False, "complex": False}

    # Assert nothing else moved.
    a = {k: v for k, v in base.items() if k not in ("dataset", "save")}
    b = {k: v for k, v in out.items() if k not in ("dataset", "save")}
    assert json.dumps(a, sort_keys=True) == json.dumps(b, sort_keys=True), \
        "%s: something other than dataset/save changed" % kind
    assert out["scenarios"] == base["scenarios"], "%s: scenario list changed" % kind

    path = os.path.join(CFGDIR, kind + ".yaml")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(HEADER.format(name=kind, src=os.path.relpath(src_path, ROOT).replace("\\", "/")))
        fh.write("\n")
        yaml.safe_dump(out, fh, sort_keys=False, default_flow_style=False, width=100)
    return path, len(out["scenarios"]), out["dataset"]["num_frames"], out["dataset"]["random_seed"]


def main():
    os.makedirs(CFGDIR, exist_ok=True)
    for kind, src in (("pilot", SRC_TRAIN), ("train", SRC_TRAIN), ("val", SRC_VAL)):
        p, n_sc, n_fr, seed = build(kind, src)
        print("%-6s -> %s   (%d scenarios, %d frames, seed %d)"
              % (kind, os.path.relpath(p, ROOT), n_sc, n_fr, seed))
    print("\ntarget-side fields verified identical to the originals for all three.")


if __name__ == "__main__":
    main()
