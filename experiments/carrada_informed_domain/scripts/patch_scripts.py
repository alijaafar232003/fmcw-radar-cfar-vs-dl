"""Generate isolated copies of the training and threshold scripts. Phase 6 preparation.

Same convention the NMS audit used (`p4_patch_carrada.py`): the originals are never edited, the
copies are auto-generated from them by a recorded set of substitutions, and the substitution list
IS the diff. Every copy lands in scripts_patched/ and writes only inside this experiment.

    python patch_scripts.py

train_tinycnn_ci.py
    * splits          bench2_train/bench2_val -> carrada_informed_train/carrada_informed_val
    * output dir      results/dl -> experiments/carrada_informed_domain/checkpoints
                      The frozen checkpoints live in results/dl. Even with a distinct --tag there
                      would be no filename collision, but this experiment must be incapable of
                      writing into that directory, not merely unlikely to.
    Nothing else: optimizer, lr, batch size, epochs, pos_weight, seeds, thread count, the
    pre-flight gates, the save-at logic and the resume logic are the originals.

derive_thresholds_ci.py
    * split           bench2_val -> carrada_informed_val
    * checkpoints     results/dl/tinycnn_frozen_s{S}_ep021.pt -> this experiment's
    * NMS radius      made an EXPLICIT parameter, and passed through to candidate extraction
    * output          experiments/carrada_informed_domain/configs/thresholds_r{N}.json

WHY THE RADIUS HAD TO BECOME EXPLICIT
-------------------------------------
`dl.infer.predict_points` declares `nms_size: int = NMS_SIZE`, and a default argument binds at
FUNCTION DEFINITION time. `dl.infer.NMS_SIZE` is 5. `collect_split` calls `predict_points` without
passing `nms_size`, so it always extracts at radius 5 regardless of what any caller sets
afterwards. The NMS audit's patched copy sets `det.NMS_SIZE = 2`, which reaches
`det.tinycnn_peaks` but NOT `collect_split` -- so the thresholds published as radius-2 were in fact
derived at radius 5, which is exactly why they are byte-identical to the radius-5 set.

This copy therefore passes the radius explicitly. It is generated for BOTH radii so the size of
the effect is measured rather than argued about:

  r=5  reproduces the Chapter 7 code path exactly, keeping the primary comparison
       (new TinyCNN vs original TinyCNN) free of a threshold-protocol difference;
  r=2  is what the stated rule asks for, as a sensitivity check.

The original `derive_tinycnn_thresholds.py` and the e6 copy are not modified, and the Chapter 7
result is not touched.
"""
from __future__ import annotations

import hashlib
import io
import json
import os
import time

HERE = os.path.dirname(os.path.abspath(__file__))
EXP = os.path.dirname(HERE)
ROOT = os.path.dirname(os.path.dirname(EXP))
DST = os.path.join(EXP, "scripts_patched")

SRC_TRAIN = os.path.join(ROOT, "scripts", "train_tinycnn.py")
SRC_THR = os.path.join(ROOT, "experiments", "r_carrada_real_data_validation",
                       "scripts", "derive_tinycnn_thresholds.py")

CKPT = (EXP + "/checkpoints").replace("\\", "/")
CFGD = (EXP + "/configs").replace("\\", "/")

BANNER = ("# " + "-" * 76 + "\n"
          "# CARRADA-INFORMED PATCH (auto-generated by scripts/patch_scripts.py -- do not edit)\n"
          "# Source: %s\n"
          "# The original is NOT modified. Substitutions are listed in the generator's docstring\n"
          "# and recorded with their counts in results/patch_manifest.json.\n"
          "# " + "-" * 76 + "\n")


def sub(text, old, new, expect, label, log):
    n = text.count(old)
    assert n == expect, "%s: expected %d occurrences of %r, found %d" % (label, expect, old, n)
    log.append({"label": label, "old": old, "new": new, "count": n})
    return text.replace(old, new)


def patch_train(log):
    t = io.open(SRC_TRAIN, encoding="utf-8").read()
    # These copies live two directories deeper than the original, so the script's own
    # `parents[1]` derivation would resolve ROOT to the experiment folder and fail to find src/.
    t = sub(t, "ROOT = Path(__file__).resolve().parents[1]",
            'ROOT = Path(r"%s")   # CI PATCH: pinned; this copy is two levels deeper'
            % ROOT.replace("\\", "/"), 1, "ROOT pin", log)
    t = sub(t, '"bench2_train"', '"carrada_informed_train"', 4, "train split", log)
    t = sub(t, '"bench2_val"', '"carrada_informed_val"', 3, "val split", log)
    t = sub(t, 'out_dir = ROOT / "results" / "dl"',
            'out_dir = Path(r"%s")   # CI PATCH: never results/dl' % CKPT,
            1, "output dir", log)
    t = sub(t, "Train the detector on `bench2_train`, validating on all of `bench2_val`.",
            "Train the detector on `carrada_informed_train`, validating on all of "
            "`carrada_informed_val`.", 1, "docstring", log)
    return BANNER % os.path.relpath(SRC_TRAIN, ROOT).replace("\\", "/") + "\n" + t


def patch_thresholds(radius, log):
    t = io.open(SRC_THR, encoding="utf-8").read()

    # Same depth problem as the trainer: this copy is one level deeper than the original, so its
    # EXP/ROOT derivation would be wrong. EXP stays pointed at the ORIGINAL CARRADA experiment,
    # because that is where `detectors.py` and the rest of its src/ live and those are read-only.
    t = sub(t, "HERE = os.path.dirname(os.path.abspath(__file__))\n"
               "EXP = os.path.dirname(HERE)\n"
               "ROOT = os.path.dirname(os.path.dirname(EXP))",
            'HERE = os.path.dirname(os.path.abspath(__file__))\n'
            'ROOT = r"%s"          # CI PATCH: pinned\n'
            'EXP = os.path.join(ROOT, "experiments", "r_carrada_real_data_validation")'
            '   # read-only: detectors.py and src/ come from the original experiment'
            % ROOT.replace("\\", "/"), 1, "ROOT/EXP pin", log)

    t = sub(t, 'SPLIT = "bench2_val"          # the ONLY dataset this script may read',
            'SPLIT = "carrada_informed_val"   # the ONLY dataset this script may read\n'
            'NMS = %d                       # CI PATCH: explicit, see patch_scripts.py' % radius,
            1, "split + explicit radius", log)

    t = sub(t, 'OUT = os.path.join(EXP, "configs", "tinycnn_zero_shot_thresholds.json")',
            'OUT = os.path.join(r"%s", "thresholds_r%d.json")' % (CFGD, radius),
            1, "output path", log)

    # Point the loader at this experiment's checkpoints, and make candidate extraction use NMS.
    t = sub(t, "import detectors as det  # noqa: E402",
            "import detectors as det  # noqa: E402\n"
            "\n"
            "# ---------------- CI PATCH: this experiment's checkpoints, and an EXPLICIT radius.\n"
            "# `collect_split` calls `predict_points` without nms_size, and that default was bound\n"
            "# to dl.infer.NMS_SIZE (=5) when the function was defined, so setting det.NMS_SIZE\n"
            "# does NOT reach it. The radius is therefore threaded through a local re-implementation\n"
            "# of collect_split that differs from the original in exactly one argument.\n"
            "_CI_CKPT = r\"%s\"\n"
            "det.NMS_SIZE = NMS_PLACEHOLDER\n"
            "det.checkpoint_path = lambda seed: os.path.join(\n"
            "    _CI_CKPT, \"tinycnn_ci_s{}_ep021.pt\".format(seed))\n"
            "\n"
            "import numpy as _np  # noqa: E402\n"
            "import pandas as _pd  # noqa: E402\n"
            "from dl.dataset import RDDataset as _RDDataset  # noqa: E402\n"
            "from dl.infer import cfar_valid_mask as _valid_mask, predict_points as _pp  # noqa: E402\n"
            "\n"
            "\n"
            "def _collect_split_at(model, split, nms_size, device=\"cpu\"):\n"
            "    \"\"\"`dl.infer.collect_split`, with nms_size passed through instead of defaulted.\"\"\"\n"
            "    ds = _RDDataset(split)\n"
            "    frames, snrs = [], []\n"
            "    for fd in ds.frame_dirs:\n"
            "        mag = _np.load(fd / \"rd_map_mag.npy\")\n"
            "        lab = _pd.read_csv(fd / \"labels.csv\")\n"
            "        truths = (lab[[\"range_bin\", \"velocity_bin\"]].to_numpy() if len(lab)\n"
            "                  else _np.zeros((0, 2)))\n"
            "        valid = _valid_mask(mag.shape)\n"
            "        points = _pp(model, mag, valid=valid, nms_size=nms_size, device=device)\n"
            "        frames.append((points, truths, mag.shape, valid))\n"
            "        snrs.append(lab[\"cell_snr_db\"].to_numpy() if len(lab) else _np.zeros(0))\n"
            "    return frames, snrs\n" % CKPT,
            1, "checkpoint + explicit collect_split", log)

    t = sub(t, "    frames, _ = collect_split(model, SPLIT)      "
               "# all 1600 frames = all 8 conditions, pooled",
            "    frames, _ = _collect_split_at(model, SPLIT, NMS)   "
            "# all 1600 frames, pooled, radius NMS",
            1, "use explicit collector", log)

    # The rule string in the original says "radius 5" unconditionally. Make it state the truth.
    t = sub(t, '"using frozen candidate extraction, frozen NMS radius 5 and the frozen valid "',
            '"using frozen candidate extraction, NMS radius {} and the frozen valid ".format(NMS) +'
            '\n                 "", ',
            1, "rule string radius", log)
    t = t.replace('"rule": ("lowest score threshold whose POOLED measured per-cell Pfa <= 1e-4 on '
                  'bench2_val, "',
                  '"rule": ("lowest score threshold whose POOLED measured per-cell Pfa <= 1e-4 on '
                  'carrada_informed_val, "')
    t = t.replace('"nms_size": det.NMS_SIZE,', '"nms_size": NMS,')
    t = t.replace("det.NMS_SIZE = NMS_PLACEHOLDER", "det.NMS_SIZE = %d" % radius)
    # The original docstring asserts radius 5 unconditionally; make it state this copy's radius.
    t = sub(t, "is <= 1e-4, using the frozen candidate extraction, frozen NMS radius 5, and the "
               "frozen valid",
            "is <= 1e-4, using the frozen candidate extraction, NMS radius %d (passed "
            "explicitly, not defaulted), and the frozen valid" % radius,
            1, "docstring radius", log)
    t = sub(t, "PREREGISTRATION §8.1, final ruling 1: one threshold per frozen seed, from "
               "`bench2_val` only,",
            "Chapter 7 rule, applied to the CARRADA-INFORMED arm: one threshold per seed, from "
            "`carrada_informed_val` only,", 1, "docstring split", log)
    return BANNER % os.path.relpath(SRC_THR, ROOT).replace("\\", "/") + "\n" + t


def main():
    os.makedirs(DST, exist_ok=True)
    os.makedirs(os.path.join(EXP, "checkpoints"), exist_ok=True)
    man = {"generated_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()), "copies": []}

    jobs = [("train_tinycnn_ci.py", SRC_TRAIN, patch_train, None),
            ("derive_thresholds_ci_r5.py", SRC_THR, patch_thresholds, 5),
            ("derive_thresholds_ci_r2.py", SRC_THR, patch_thresholds, 2)]

    for name, src, fn, arg in jobs:
        log = []
        text = fn(log) if arg is None else fn(arg, log)
        p = os.path.join(DST, name)
        io.open(p, "w", encoding="utf-8", newline="").write(text)
        compile(text, p, "exec")                     # syntax-check the generated file
        man["copies"].append({
            "file": "scripts_patched/" + name,
            "source": os.path.relpath(src, ROOT).replace("\\", "/"),
            "source_sha256": hashlib.sha256(open(src, "rb").read()).hexdigest(),
            "patched_sha256": hashlib.sha256(open(p, "rb").read()).hexdigest(),
            "radius": arg,
            "substitutions": log,
        })
        print("%-28s <- %-56s  %d substitutions"
              % (name, os.path.relpath(src, ROOT).replace("\\", "/"), len(log)))

    mp = os.path.join(EXP, "results", "patch_manifest.json")
    os.makedirs(os.path.dirname(mp), exist_ok=True)
    with open(mp, "w", encoding="utf-8") as fh:
        json.dump(man, fh, indent=1)
    print("\nwrote", os.path.relpath(mp, ROOT))


if __name__ == "__main__":
    main()
